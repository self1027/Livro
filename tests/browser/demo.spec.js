test('automático pode ser pausado e restaurado sem cadastrar registros duplicados',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Assistir automaticamente',exact:true}).click()
  await expect(page.locator('.demo-guide-top')).toContainText('PASSO 2 DE 23',{timeout:10000})
  await page.getByRole('button',{name:'Pausar',exact:true}).click()
  await page.waitForTimeout(7000)
  await expect(page.locator('.demo-guide-top')).toContainText('PASSO 2 DE 23')
  await page.reload();await expect(page.locator('.demo-guide-top')).toContainText('PASSO 2 DE 23')
  await page.locator('[data-tour-next]').click()
  await expect(page.locator('.demo-guide-top')).toContainText('PASSO 3 DE 23')
  await page.locator('#demo-guide').getByRole('button',{name:'Voltar',exact:true}).click()
  await page.locator('[data-tour-next]').click()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('livro-demo-v2')).complaints.length)).toBe(49)
  page.on('dialog',d=>d.accept());await page.getByRole('button',{name:'Restaurar dados',exact:true}).click()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('livro-demo-v2')).complaints.length)).toBe(48)
})

